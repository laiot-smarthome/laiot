<?php

declare(strict_types=1);

/**
 * WebSocket-сервер LaIOT.
 *
 * Сервер только отправляет данные: клиент не присылает команды в сокет.
 * Подписка на свойства приходит в короткоживущем тикете, который выдаёт
 * HTTP-эндпоинт панели после проверки сессии. Тикет содержит пары
 * «объект:свойство», поэтому страница подписывается только на то, что
 * действительно показано в её разметке.
 *
 * 2026-10-29 — секция добавлена для сервера исходящих изменений свойств.
 */
return [
    // Сокет выключен — HTTP-тикет отвечает 503, команда websocket не стартует.
    'enabled' => true,

    // Слушатель Workerman. В production его закрывает nginx и проксирует
    // /websocket на этот адрес; наружу порт обычно не публикуется.
    'host' => '127.0.0.1',
    'port' => 8081,
    'path' => '/websocket',

    // Публичный адрес для браузера. Пусто — тот же хост и протокол, что у
    // панели (рассчитано на проксирование через nginx по /websocket).
    'public_url' => '',

    // Число процессов-обработчиков. На Windows Workerman работает в одном
    // процессе, команда принудительно ставит 1; production — Linux.
    'workers' => 2,

    // Срок жизни тикета подключения. Тикет одноразовый по смыслу страницы,
    // но в пределах TTL допускает переподключение вкладки.
    'ticket_ttl' => 300,

    // Как часто процесс читает outbox websocket_events.
    'poll_ms' => 100,

    // Сколько событий забирать из outbox за один проход и отдавать в одном
    // пакете; при отставании процесс догоняет следующими проходами.
    'batch' => 500,
    'replay_limit' => 500,

    // Ограничения одного подключения и одного процесса.
    'max_channels' => 2048,
    'max_connections' => 1000,

    // Периодические задачи сервера, секунды.
    'heartbeat' => 25,
    'auth_check' => 30,
    'prune_interval' => 300,

    // Сколько часов хранить outbox. Сервер при старте читает только новые
    // события, поэтому старые строки нужны лишь для диагностики.
    'retention_hours' => 24,

    // Пусто — взять хост из public_url, BASE_URL или Host подключения.
    // Разрешаются корневой домен и все его поддомены.
    'root_domain' => '',

    // Точные origin через запятую. Если заданы, заменяют правило корневого
    // домена, например https://home.example.
    'allowed_origins' => '',
];
