<?php

declare(strict_types=1);

namespace MajorDoMo\Mqtt;

/**
 * Интеграция, которая живёт на общем MQTT-соединении модуля MQTT.
 *
 * Модуль-интеграция (например, Zigbee) не открывает собственный клиент и не
 * дублирует подписку: он объявляет свои фильтры, получает владение топиком и
 * сам решает, как доставить сообщение своему worker-у. MQTT-цикл при этом
 * работает только транспортом: принял пакет, отдал владельцу, пошёл дальше.
 *
 * `enqueue()` обязан быть быстрым и долговечным: цикл приёма не ждёт разбора
 * сообщения. Интеграция кладёт задание в свою очередь, а тяжёлую работу
 * выполняет её worker. Ошибка постановки задания логируется MQTT-циклом и не
 * роняет соединение с брокером.
 *
 * 2026-10-28 — контракт создан при переносе Zigbee на общий транспорт.
 */
interface Integration
{
    /** Стабильный id модуля-владельца, например `zigbee`. */
    public function id(): string;

    /**
     * MQTT-фильтры для подписки, например `zigbee2mqtt/#`.
     *
     * @return list<string>
     */
    public function topics(): array;

    /** Принадлежит ли входящий топик этой интеграции. */
    public function owns(string $topic): bool;

    /**
     * Передаёт сообщение в долговечную очередь модуля.
     *
     * Вызывается в процессе приёма MQTT. Исключение не должно оставлять
     * систему в неопределённом состоянии: цикл зафиксирует ошибку в
     * RuntimeState и продолжит приём.
     */
    public function enqueue(string $topic, string $payload): void;
}
